"""Generate dependency-free browser catalog from the Python package's JSON."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'blob_filename_fix/messages.json').read_text(encoding='utf-8'))
output = '// Generated by tools/generate_messages.py; do not edit.\nexport const messages = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
path = root / 'web/messages.mjs'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if path.read_text(encoding='utf-8') != output:
        raise SystemExit('Browser message catalog is out of sync')
else:
    path.write_text(output, encoding='utf-8')
